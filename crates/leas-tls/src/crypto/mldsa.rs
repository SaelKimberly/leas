//! `ML-DSA-65` verification for REALITY's post-quantum certificate extension.
//!
//! Xray signs `HMAC-SHA512(auth_key, ed25519_pub ‖ ClientHello.Raw ‖
//! ServerHello.Raw)` with its `mldsa65_seed` key and ships the signature in
//! the certificate's FIRST X.509 extension
//! (`thirdparty/Xray-core/transport/internet/reality/reality.go:111-127`).
//! FIPS 204 verify with the empty context string, which is what Go's
//! `mldsa.Verify(pk, msg, sig, nil)` does.
//!
//! Verify-only: the crate's signing half and its RNG are never linked, so no
//! secret key material can be produced here.

use ml_dsa::{EncodedSignature, EncodedVerifyingKey, MlDsa65, Signature, VerifyingKey};

/// FIPS 204 ML-DSA-65 public key length (`pkEncode`).
pub const MLDSA65_PUBLIC_KEY_LEN: usize = 1952;
/// FIPS 204 ML-DSA-65 signature length (`sigEncode`).
pub const MLDSA65_SIGNATURE_LEN: usize = 3309;

/// Verify a detached ML-DSA-65 signature over `message` with the empty
/// FIPS 204 context string.
///
/// A wrong-length key or signature is a `false` here — callers turn that into
/// a REALITY rejection, never a fallback to the HMAC-only rule.
#[must_use]
pub fn verify(public_key: &[u8], message: &[u8], signature: &[u8]) -> bool {
    if public_key.len() != MLDSA65_PUBLIC_KEY_LEN || signature.len() != MLDSA65_SIGNATURE_LEN {
        return false;
    }
    let Ok(encoded_key) = EncodedVerifyingKey::<MlDsa65>::try_from(public_key) else {
        return false;
    };
    let Ok(encoded_sig) = EncodedSignature::<MlDsa65>::try_from(signature) else {
        return false;
    };
    let Some(sig) = Signature::<MlDsa65>::decode(&encoded_sig) else {
        return false;
    };
    VerifyingKey::<MlDsa65>::decode(&encoded_key).verify_with_context(message, &[], &sig)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Independent oracle: key + message + signature generated by Go 1.27's
    /// `crypto/mldsa` (the package Xray links), pinned as hex. A Rust-only
    /// round trip would prove nothing about FIPS 204 conformance.
    const GO_PUBKEY: &str = include_str!("../../tests/fixtures/mldsa65_pub.hex");
    const GO_MESSAGE: &str = include_str!("../../tests/fixtures/mldsa65_msg.hex");
    const GO_SIGNATURE: &str = include_str!("../../tests/fixtures/mldsa65_sig.hex");

    fn unhex(s: &str) -> Vec<u8> {
        let s = s.trim();
        (0..s.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&s[i..i + 2], 16).expect("hex"))
            .collect()
    }

    #[test]
    fn verifies_a_go_generated_signature() {
        let pk = unhex(GO_PUBKEY);
        let msg = unhex(GO_MESSAGE);
        let sig = unhex(GO_SIGNATURE);
        assert_eq!(pk.len(), MLDSA65_PUBLIC_KEY_LEN);
        assert_eq!(sig.len(), MLDSA65_SIGNATURE_LEN);
        assert!(verify(&pk, &msg, &sig), "FIPS 204 verify must accept");
    }

    #[test]
    fn rejects_tampered_inputs() {
        let pk = unhex(GO_PUBKEY);
        let msg = unhex(GO_MESSAGE);
        let sig = unhex(GO_SIGNATURE);

        let mut bad_msg = msg.clone();
        bad_msg[0] ^= 0x01;
        assert!(!verify(&pk, &bad_msg, &sig), "message tamper");

        let mut bad_sig = sig.clone();
        bad_sig[0] ^= 0x01;
        assert!(!verify(&pk, &msg, &bad_sig), "signature tamper");

        let mut bad_pk = pk.clone();
        bad_pk[0] ^= 0x01;
        assert!(!verify(&bad_pk, &msg, &sig), "key tamper");

        assert!(!verify(&pk[..100], &msg, &sig), "short key");
        assert!(!verify(&pk, &msg, &sig[..100]), "short signature");
    }
}
